import type { ConversationLogEntry } from '@rebecca/types';
import type { IMemoryEpisodicStore, TurnWithInnerThought } from './types';

/** Default sliding window size in user/model turn pairs kept in active working memory. */
export const DEFAULT_WORKING_MEMORY_LIMIT = 10;

const DEFAULT_MEMORY_TIMEZONE = 'Asia/Tokyo';

const formatEntryTimestamp = (
  isoTimestamp: string | undefined,
  timezone: string = DEFAULT_MEMORY_TIMEZONE,
): string => {
  if (!isoTimestamp) return '';
  const date = new Date(isoTimestamp);
  if (Number.isNaN(date.getTime())) return '';

  const formatter = new Intl.DateTimeFormat('ja-JP', {
    timeZone: timezone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
    timeZoneName: 'short',
  });

  return formatter.format(date).replace(/\//g, '-');
};

/**
 * Extracts a bounded sliding window of recent interactions from the episodic buffer.
 *
 * @param episodicBuffer - Full chronological conversation log entries, or `undefined`.
 * @param limit - Maximum number of turn pairs (`2 * limit` entries) to retain. Defaults to `10`.
 * @returns Trailing slice of conversation entries, or `[]` when buffer is empty or `limit <= 0`.
 */
export const getWorkingMemory = (
  episodicBuffer: readonly ConversationLogEntry[] | undefined,
  limit: number = DEFAULT_WORKING_MEMORY_LIMIT,
): ConversationLogEntry[] => {
  if (!episodicBuffer || episodicBuffer.length === 0 || limit <= 0) {
    return [];
  }
  return episodicBuffer.slice(-limit * 2);
};

/**
 * Constructs a synchronized `[user, model]` turn pair ready for episodic persistence.
 * Preserves the persona's private `thought` (Honne) alongside the spoken `reply` (Tatemae).
 *
 * @param userText - Normalized input text from the user.
 * @param modelText - Final spoken reply text generated by the persona.
 * @param thought - Optional internal monologue produced alongside the reply.
 * @param timestamp - Optional ISO 8601 timestamp string (defaults to current UTC instant).
 * @returns Tuple containing the user entry and model entry.
 */
export const createTurnPair = (
  userText: string,
  modelText: string,
  thought?: string,
  timestamp: string = new Date().toISOString(),
): [ConversationLogEntry, ConversationLogEntry] => {
  const userEntry: ConversationLogEntry = {
    role: 'user',
    content: userText,
    timestamp,
  };

  const trimmedThought = typeof thought === 'string' && thought.trim() !== '' ? thought : undefined;
  const modelEntry: ConversationLogEntry = trimmedThought
    ? {
        role: 'model',
        content: modelText,
        thought: trimmedThought,
        timestamp,
      }
    : {
        role: 'model',
        content: modelText,
        timestamp,
      };

  return [userEntry, modelEntry];
};

/**
 * Appends a user/model interaction pair (including optional inner thought) to an episodic store.
 *
 * @param store - Persistence adapter implementing `appendEpisodicBuffer`.
 * @param userId - Canonical user identifier within the target memory channel.
 * @param userText - Input message from the user.
 * @param modelText - Spoken reply delivered by the persona.
 * @param thought - Optional internal monologue (`thought`) attached to the model turn.
 * @param now - Optional timestamp override (defaults to `new Date()`).
 */
export const saveInteraction = async (
  store: IMemoryEpisodicStore,
  userId: string,
  userText: string,
  modelText: string,
  thought?: string,
  now: Date = new Date(),
): Promise<void> => {
  if (!userId.trim()) {
    throw new Error('Cannot save interaction: userId must be a non-empty string');
  }
  const [userEntry, modelEntry] = createTurnPair(userText, modelText, thought, now.toISOString());
  await store.appendEpisodicBuffer(userId, userEntry);
  await store.appendEpisodicBuffer(userId, modelEntry);
};

/**
 * Formats a single conversation log entry into Tatemae/Honne LLM turn text.
 * Restores stored `thought` on model entries as `【思考・本音】...\n【発話】...` and prepends
 * localized `[YYYY-MM-DD HH:mm TZ]` timestamps when available.
 *
 * @param entry - Episodic conversation log entry.
 * @param timezone - IANA timezone identifier for formatting timestamps. Defaults to `'Asia/Tokyo'`.
 * @returns Provider-agnostic turn representation preserving role and inner thought framing.
 */
export const formatTurnWithInnerThought = (
  entry: ConversationLogEntry,
  timezone: string = DEFAULT_MEMORY_TIMEZONE,
): TurnWithInnerThought => {
  const formattedTime = formatEntryTimestamp(entry.timestamp, timezone);
  const timePrefix = formattedTime ? `[${formattedTime}] ` : '';

  if (entry.role === 'model') {
    const modelBody = entry.thought
      ? `【思考・本音】${entry.thought}\n【発話】${entry.content}`
      : entry.content;
    return {
      role: 'model',
      text: `${timePrefix}${modelBody}`,
    };
  }

  return {
    role: 'user',
    text: `${timePrefix}${entry.content}`,
  };
};

/**
 * Converts a chronological history slice into Tatemae/Honne formatted turns for LLM prompting.
 *
 * @param history - Recent working memory turns.
 * @param timezone - IANA timezone identifier for timestamp prefixes. Defaults to `'Asia/Tokyo'`.
 * @returns Immutable array of formatted conversation turns ready to map to SDK message parts.
 */
export const formatHistoryWithInnerThought = (
  history: readonly ConversationLogEntry[],
  timezone: string = DEFAULT_MEMORY_TIMEZONE,
): TurnWithInnerThought[] => {
  return history.map((entry) => formatTurnWithInnerThought(entry, timezone));
};
